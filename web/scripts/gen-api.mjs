import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import nextEnv from "@next/env";
import { astToString, default as openapiTS } from "openapi-typescript";

nextEnv.loadEnvConfig(process.cwd());

function resolveSpecSource() {
    if (process.argv[2]) {
        return {
            type: "cli-arg",
            source: process.argv[2],
        };
    }

    const envSpec =
        process.env.OPENAPI_SPEC ||
        process.env.OPENAPI_FILE ||
        process.env.OPENAPI_PATH;
    if (envSpec) {
        return {
            type: "env",
            source: envSpec,
        };
    }

    const candidateLocalFiles = [
        resolve(process.cwd(), "../docs/api/openapi.json"),
        resolve(process.cwd(), "../docs/openapi.json"),
        resolve(process.cwd(), "docs/openapi.json"),
        resolve(process.cwd(), "../docs/openapi/v1.json"),
        resolve(process.cwd(), "docs/openapi/v1.json"),
        resolve(process.cwd(), "../openapi.json"),
        resolve(process.cwd(), "openapi.json"),
    ];

    for (const candidate of candidateLocalFiles) {
        if (existsSync(candidate)) {
            return {
                type: "local-file",
                source: candidate,
            };
        }
    }

    const apiUrl = (process.env.API_URL || "http://localhost:5080").replace(
        /\/+$/,
        "",
    );
    return {
        type: "remote-url",
        source: `${apiUrl}/openapi/v1.json`,
    };
}

const resolved = resolveSpecSource();
const outputDir = resolve(process.cwd(), "src/lib/api/generated");
const outputPath = resolve(outputDir, "schema.d.ts");
const indexPath = resolve(outputDir, "index.ts");
const readmePath = resolve(outputDir, "README.md");

console.info(
    `[gen:api] Resolving OpenAPI specification from [${resolved.type}]: ${resolved.source}`,
);

let schemaInput;
let displaySource = resolved.source;

if (
    resolved.type === "local-file" ||
    (typeof resolved.source === "string" && existsSync(resolved.source))
) {
    const fileContent = await readFile(resolved.source, "utf8");
    schemaInput = JSON.parse(fileContent);
    displaySource = resolved.source;
} else if (
    typeof resolved.source === "string" &&
    (resolved.source.startsWith("http://") ||
        resolved.source.startsWith("https://"))
) {
    schemaInput = resolved.source;
    displaySource = resolved.source;
} else {
    // If it's a path or URL
    try {
        schemaInput = pathToFileURL(resolved.source);
    } catch {
        schemaInput = resolved.source;
    }
}

const schemaAst = await openapiTS(schemaInput);
const banner = [
    "/**",
    " * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY.",
    " *",
    " * Generated by openapi-typescript from OpenAPI specification.",
    " * To regenerate, run in the web directory:",
    " *   npm run gen:api",
    " */",
    "",
    astToString(schemaAst),
].join("\n");

await mkdir(outputDir, { recursive: true });
await writeFile(outputPath, banner, "utf8");

const indexContent = [
    "/**",
    " * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY.",
    " *",
    " * Re-exports API schema types.",
    " * To regenerate, run in the web directory:",
    " *   npm run gen:api",
    " */",
    "",
    'export type * from "./schema";',
    "",
].join("\n");
await writeFile(indexPath, indexContent, "utf8");

const readmeContent = [
    "# Generated API Client Types",
    "",
    "> **DO NOT EDIT ANY FILES IN THIS DIRECTORY MANUALLY.**",
    ">",
    "> All files in `src/lib/api/generated/` are automatically produced by `openapi-typescript`",
    "> from the committed OpenAPI specification (`docs/api/openapi.json`).",
    "> Any manual modifications will be overwritten and will cause CI verification to fail.",
    "",
    "## How to Regenerate",
    "",
    "Whenever the OpenAPI specification (`docs/api/openapi.json`) changes, update the types with:",
    "",
    "```bash",
    "npm run gen:api",
    "```",
    "",
    "Commit both `docs/api/openapi.json` and the updated `src/lib/api/generated/` together.",
    "",
].join("\n");
await writeFile(readmePath, readmeContent, "utf8");

console.info(`[gen:api] Successfully generated API types at: ${outputPath}`);
